package dev.burmaldyn.api;

/**
 * Тип склонения, по которому изменяется слово-исключение.
 *
 * <p>Используется в обе стороны: чтобы понять падеж исходного слова
 * («жены» → родительный) и чтобы поставить слово-замену в тот же падеж
 * («жинки»).</p>
 */
public enum Declension {
	/** Мужской род с основой на согласный: {@code дод}, {@code сыр}, {@code батч}. */
	MASCULINE,
	/** Женский род на -а/-я: {@code жинка}, {@code папа}. */
	FEMININE_A,
	/** Слово не склоняется — во всех падежах одна и та же форма. */
	INDECLINABLE
}
