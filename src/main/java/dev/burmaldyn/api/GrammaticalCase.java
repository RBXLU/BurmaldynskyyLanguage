package dev.burmaldyn.api;

/**
 * Падеж, который морфологический анализатор определил у русского слова.
 *
 * <p>Бурмалдинское слово склоняется как обычное существительное на «-ость»
 * («хвостость», «хвостости», «хвостостью»), поэтому падеж исходного слова
 * нужно сохранять — именно он решает, какое окончание получит результат.</p>
 */
public enum GrammaticalCase {
	/** Именительный: кто? что? */
	NOMINATIVE,
	/** Родительный: кого? чего? */
	GENITIVE,
	/** Дательный: кому? чему? */
	DATIVE,
	/** Винительный: кого? что? */
	ACCUSATIVE,
	/** Творительный: кем? чем? */
	INSTRUMENTAL,
	/** Предложный: о ком? о чём? */
	PREPOSITIONAL
}
