	/** Проверяет, что символ — русская буква. */
	public static boolean isCyrillic(final char c) {
		return (c >= 'а' && c <= 'я') || (c >= 'А' && c <= 'Я') || c == 'ё' || c == 'Ё';
	}

	/** Проверяет, что слово оканчивается на гласную. */
	public static boolean endsWithVowel(final String word) {
		return !word.isEmpty() && VOWELS.indexOf(word.charAt(word.length() - 1)) >= 0;
	}

	public static boolean endsWithAny(final String word, final String[] endings) {
		for (String ending : endings) {
			if (word.endsWith(ending)) {
				return true;
			}
		}

		return false;
	}
